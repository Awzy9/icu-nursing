import { createHash } from "node:crypto";
import raw from "@icu/fixtures/questions.json";
import type { Localized } from "./types";

/**
 * DEVELOPMENT FIXTURES: clearly labelled, synthetic and NONCLINICAL practice questions (astronomy, arithmetic, grammar,
 * fictional rules...). They exist only to exercise the question-bank engine. They are not ICU content, are not derived from
 * the clinical draft MCQs, and must never be mixed with them.
 */
export const SYNTHETIC_LABEL = "SYNTHETIC FIXTURE";
export const SYNTHETIC_SOURCE_NOTE = `${SYNTHETIC_LABEL} — nonclinical sample item written for software testing. Not clinical content.`;

/** Stable UUID-shaped ids derived from the question code, so the TS fixtures and the SQL seed agree. */
export function stableId(name: string): string {
  const h = createHash("md5").update(name).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

export interface FixtureQuestion {
  id: string;
  code: string;
  domainSlug: string;
  difficulty: number;
  version: number;
  stem: Localized;
  options: { id: string; position: number; text: Localized; explanation: Localized }[];
  correctOptionId: string;
  rationale: Localized;
}

interface RawQuestion {
  code: string;
  domain: string;
  difficulty: number;
  stem: Localized;
  options: Localized[];
  correct: number;
  explanations: Localized[];
  rationale: Localized;
}

export function loadFixtures(): FixtureQuestion[] {
  const out = (raw as RawQuestion[]).map((q) => {
    if (!/^SYN-\d{3}$/.test(q.code)) throw new Error(`fixture code must look like SYN-001, got ${q.code}`);
    if (q.options.length !== 4 || q.explanations.length !== 4) throw new Error(`${q.code}: four options and four explanations required`);
    if (!/no clinical content/i.test(q.rationale.en ?? "")) throw new Error(`${q.code}: rationale must state that the item has no clinical content`);
    const options = q.options.map((text, i) => ({ id: stableId(`${q.code}:o${i + 1}`), position: i + 1, text, explanation: q.explanations[i]! }));
    return {
      id: stableId(q.code),
      code: q.code,
      domainSlug: q.domain,
      difficulty: q.difficulty,
      version: 1,
      stem: q.stem,
      options,
      correctOptionId: options[q.correct]!.id,
      rationale: q.rationale,
    };
  });
  if (new Set(out.map((q) => q.id)).size !== out.length) throw new Error("duplicate fixture ids");
  return out;
}

/** SQL that loads the fixtures into a DEVELOPMENT database as demo_synthetic questions (published, hidden until the app setting is on). */
export function fixtureSeedSql(opts: { makeVisible: boolean }): string {
  const lit = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  const str = (v: string) => `'${v.replace(/'/g, "''")}'`;
  const lines = [
    "-- GENERATED by scripts/seed-synthetic-questions.ts - do not edit by hand.",
    "-- DEVELOPMENT ONLY: synthetic, NONCLINICAL fixtures (kind = demo_synthetic). Never run against production.",
    "begin;",
  ];
  for (const q of loadFixtures()) {
    // Published questions are immutable, so each question is loaded once; re-running the seed leaves existing questions untouched.
    lines.push(`do $seed$ begin if not exists (select 1 from public.question_items where id = ${str(q.id)}::uuid) then`);
    lines.push(
      `insert into public.question_items (id, code, kind, status, origin, domain_id, difficulty, stem, source_note, version)
  select ${str(q.id)}::uuid, ${str(q.code)}, 'demo_synthetic', 'draft', 'human', d.id, ${q.difficulty}, ${lit(q.stem)}, ${str(SYNTHETIC_SOURCE_NOTE)}, ${q.version}
  from public.nursing_domains d where d.slug = ${str(q.domainSlug)};`,
    );
    for (const o of q.options) {
      lines.push(`insert into public.question_options (id, question_id, position, text) values (${str(o.id)}::uuid, ${str(q.id)}::uuid, ${o.position}, ${lit(o.text)});`);
    }
    lines.push(`insert into public.question_answer_keys (question_id, correct_option_id, rationale) values (${str(q.id)}::uuid, ${str(q.correctOptionId)}::uuid, ${lit(q.rationale)});`);
    for (const o of q.options) {
      lines.push(`insert into public.question_explanations (option_id, question_id, explanation) values (${str(o.id)}::uuid, ${str(q.id)}::uuid, ${lit(o.explanation)});`);
    }
    lines.push(`update public.question_items set status = 'published', approved_at = now(), published_at = now() where id = ${str(q.id)}::uuid;`);
    lines.push("end if; end $seed$;");
  }
  if (opts.makeVisible) {
    lines.push("do $vis$ begin if (select environment from public.app_settings) <> 'development' then raise exception 'refusing to show fixtures: app_settings.environment is not development'; end if; end $vis$;");
    lines.push("update public.app_settings set question_fixtures_visible = true;");
  }
  lines.push("commit;");
  return lines.join("\n") + "\n";
}
