import { stableId, SYNTHETIC_SOURCE_NOTE } from "@/lib/question-bank/fixtures";
import type { CaseScope } from "./types";
import raw from "./synthetic-cases.json";

type L = Record<string, string>;
export interface CaseFixture {
  id: string; code: string; domainSlug: string; difficulty: number; version: number; title: L; vignette: L;
  steps: { id: string; position: number; info: L; prompt: L; options: { id: string; position: number; text: L; points: number; next: number | null; scope: CaseScope; feedback: L }[] }[];
}
interface RawCase {
  code: string; domain: string; difficulty: number; title: L; vignette: L;
  steps: { info: L; prompt: L; options: { text: L; points: number; next: number | null; scope: CaseScope; feedback: L }[] }[];
}

/** Synthetic, NONCLINICAL branching cases for development. Never derived from the clinical drafts. */
export function loadCaseFixtures(): CaseFixture[] {
  return (raw as RawCase[]).map((c) => {
    if (!/^SYN-CASE-\d{3}$/.test(c.code)) throw new Error(`case fixture code must look like SYN-CASE-001, got ${c.code}`);
    if (!/no clinical content/i.test(c.vignette.en ?? "")) throw new Error(`${c.code}: vignette must state that it contains no clinical content`);
    return {
      id: stableId(c.code), code: c.code, domainSlug: c.domain, difficulty: c.difficulty, version: 1, title: c.title, vignette: c.vignette,
      steps: c.steps.map((s, si) => ({
        id: stableId(`${c.code}:s${si + 1}`), position: si + 1, info: s.info, prompt: s.prompt,
        options: s.options.map((o, oi) => ({ id: stableId(`${c.code}:s${si + 1}:o${oi + 1}`), position: oi + 1, text: o.text, points: o.points, next: o.next, scope: o.scope, feedback: o.feedback })),
      })),
    };
  });
}

export function caseSeedSql(): string {
  const lit = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  const str = (v: string) => `'${v.replace(/'/g, "''")}'`;
  const out = ["-- GENERATED by scripts/seed-synthetic-questions.ts - do not edit by hand.", "-- DEVELOPMENT ONLY: synthetic, NONCLINICAL case fixtures (kind = demo_synthetic).", "begin;"];
  for (const c of loadCaseFixtures()) {
    out.push(`do $seed$ begin if not exists (select 1 from public.case_items where id = ${str(c.id)}::uuid) then`);
    out.push(`insert into public.case_items (id, code, kind, status, origin, domain_id, difficulty, title, vignette, source_note, version)
  select ${str(c.id)}::uuid, ${str(c.code)}, 'demo_synthetic', 'draft', 'human', d.id, ${c.difficulty}, ${lit(c.title)}, ${lit(c.vignette)}, ${str(SYNTHETIC_SOURCE_NOTE)}, ${c.version}
  from public.nursing_domains d where d.slug = ${str(c.domainSlug)};`);
    for (const s of c.steps) {
      out.push(`insert into public.case_steps (id, case_id, position, info, prompt) values (${str(s.id)}::uuid, ${str(c.id)}::uuid, ${s.position}, ${lit(s.info)}, ${lit(s.prompt)});`);
      for (const o of s.options) {
        out.push(`insert into public.case_step_options (id, case_id, step_id, position, text) values (${str(o.id)}::uuid, ${str(c.id)}::uuid, ${str(s.id)}::uuid, ${o.position}, ${lit(o.text)});`);
        out.push(`insert into public.case_option_keys (option_id, case_id, step_id, points, next_position, scope, feedback) values (${str(o.id)}::uuid, ${str(c.id)}::uuid, ${str(s.id)}::uuid, ${o.points}, ${o.next ?? "null"}, ${str(o.scope)}, ${lit(o.feedback)});`);
      }
    }
    out.push(`update public.case_items set status = 'published', approved_at = now(), published_at = now() where id = ${str(c.id)}::uuid;`);
    out.push("end if; end $seed$;");
  }
  out.push("commit;");
  return out.join("\n") + "\n";
}
