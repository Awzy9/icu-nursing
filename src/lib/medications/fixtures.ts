import { stableId, SYNTHETIC_SOURCE_NOTE } from "@/lib/question-bank/fixtures";
import { medicationTextViolation } from "./no-dosing";
import raw from "@icu/fixtures/medications.json";
import type { MedicationCategory } from "./types";

type L = Record<string, string>;
type LL = Record<string, string[]>;
type Kind = "observe" | "assess" | "laboratory" | "escalate" | "document";
type Support = "sourced" | "partial" | "local_protocol";
export interface MedicationFixture {
  id: string; code: string; category: MedicationCategory; highAlert: boolean; version: number; name: L; drugClass: L; summary: L;
  sections: Record<string, LL>; sectionSupport: Record<string, string>; revision: L;
  monitoring: { id: string; position: number; kind: Kind; text: L; critical: boolean; support: Support }[];
}
interface RawMed {
  code: string; category: MedicationCategory; highAlert: boolean; name: L; drugClass: L; summary: L; sections: Record<string, LL>; sectionSupport: Record<string, string>;
  revision: L; monitoring: { kind: Kind; text: L; critical: boolean; support: Support }[];
}

/** Synthetic, NONCLINICAL medication entries for development (fictional agents). Never derived from the clinical medication drafts. */
export function loadMedicationFixtures(): MedicationFixture[] {
  return (raw as unknown as RawMed[]).map((m) => {
    if (!/^SYN-MED-\d{3}$/.test(m.code)) throw new Error(`medication fixture code must look like SYN-MED-001, got ${m.code}`);
    if (!/no clinical content/i.test(m.summary.en ?? "")) throw new Error(`${m.code}: summary must state that it contains no clinical content`);
    const bad = medicationTextViolation(JSON.stringify([m.name, m.drugClass, m.summary, m.sections, m.monitoring]));
    if (bad) throw new Error(`${m.code}: fixture contains ${bad}`);
    return {
      id: stableId(m.code), code: m.code, category: m.category, highAlert: m.highAlert, version: 1, name: m.name, drugClass: m.drugClass, summary: m.summary,
      sections: m.sections, sectionSupport: m.sectionSupport, revision: m.revision,
      monitoring: m.monitoring.map((x, i) => ({ id: stableId(`${m.code}:m${i + 1}`), position: i + 1, ...x })),
    };
  });
}

export function medicationSeedSql(): string {
  const lit = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  const str = (v: string) => `'${v.replace(/'/g, "''")}'`;
  const out = ["-- GENERATED by scripts/seed-synthetic-questions.ts - do not edit by hand.", "-- DEVELOPMENT ONLY: synthetic, NONCLINICAL medication fixtures (kind = demo_synthetic; fictional agents).", "begin;"];
  for (const m of loadMedicationFixtures()) {
    out.push(`do $seed$ begin if not exists (select 1 from public.medication_items where id = ${str(m.id)}::uuid) then`);
    out.push(`insert into public.medication_items (id, code, kind, status, origin, category, high_alert, name, drug_class, summary, sections, section_support, source_note, version)
  values (${str(m.id)}::uuid, ${str(m.code)}, 'demo_synthetic', 'draft', 'human', ${str(m.category)}, ${m.highAlert}, ${lit(m.name)}, ${lit(m.drugClass)}, ${lit(m.summary)}, ${lit(m.sections)}, ${lit(m.sectionSupport)}, ${str(SYNTHETIC_SOURCE_NOTE)}, ${m.version});`);
    for (const c of m.monitoring) {
      out.push(`insert into public.medication_monitoring_items (id, medication_id, position, kind, text, critical, support) values (${str(c.id)}::uuid, ${str(m.id)}::uuid, ${c.position}, ${str(c.kind)}, ${lit(c.text)}, ${c.critical}, ${str(c.support)});`);
    }
    out.push(`insert into public.medication_revisions (medication_id, version, summary) values (${str(m.id)}::uuid, ${m.version}, ${lit(m.revision)});`);
    out.push(`update public.medication_items set status = 'published', approved_at = now(), published_at = now() where id = ${str(m.id)}::uuid;`);
    out.push("end if; end $seed$;");
  }
  out.push("commit;");
  return out.join("\n") + "\n";
}
