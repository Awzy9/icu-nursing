import { stableId, SYNTHETIC_SOURCE_NOTE } from "@/lib/question-bank/fixtures";
import raw from "@icu/fixtures/skills.json";
import type { SkillCategory } from "./types";

type L = Record<string, string>;
type LL = Record<string, string[]>;
type Phase = "preparation" | "assessment" | "procedure" | "monitoring" | "escalation" | "documentation";
type Support = "sourced" | "partial" | "local_protocol";
export interface SkillFixture {
  id: string; code: string; category: SkillCategory; version: number; title: L; summary: L; objectives: LL; prerequisites: LL;
  sections: Record<string, LL>; sectionSupport: Record<string, string>; revision: L;
  checklist: { id: string; position: number; phase: Phase; text: L; critical: boolean; support: Support }[];
}
interface RawSkill {
  code: string; category: SkillCategory; title: L; summary: L; objectives: LL; prerequisites: LL; sections: Record<string, LL>; sectionSupport: Record<string, string>;
  revision: L; checklist: { phase: Phase; text: L; critical: boolean; support: Support }[];
}

/** Synthetic, NONCLINICAL skills for development. Never derived from the clinical skill drafts under content/drafts/skills. */
export function loadSkillFixtures(): SkillFixture[] {
  return (raw as unknown as RawSkill[]).map((s) => {
    if (!/^SYN-SKILL-\d{3}$/.test(s.code)) throw new Error(`skill fixture code must look like SYN-SKILL-001, got ${s.code}`);
    if (!/no clinical content/i.test(s.summary.en ?? "")) throw new Error(`${s.code}: summary must state that it contains no clinical content`);
    return {
      id: stableId(s.code), code: s.code, category: s.category, version: 1, title: s.title, summary: s.summary, objectives: s.objectives, prerequisites: s.prerequisites,
      sections: s.sections, sectionSupport: s.sectionSupport, revision: s.revision,
      checklist: s.checklist.map((c, i) => ({ id: stableId(`${s.code}:c${i + 1}`), position: i + 1, ...c })),
    };
  });
}

export function skillSeedSql(): string {
  const lit = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  const str = (v: string) => `'${v.replace(/'/g, "''")}'`;
  const out = ["-- GENERATED by scripts/seed-synthetic-questions.ts - do not edit by hand.", "-- DEVELOPMENT ONLY: synthetic, NONCLINICAL skill fixtures (kind = demo_synthetic).", "begin;"];
  for (const s of loadSkillFixtures()) {
    out.push(`do $seed$ begin if not exists (select 1 from public.skill_items where id = ${str(s.id)}::uuid) then`);
    out.push(`insert into public.skill_items (id, code, kind, status, origin, category, title, summary, objectives, prerequisites, sections, section_support, source_note, version)
  values (${str(s.id)}::uuid, ${str(s.code)}, 'demo_synthetic', 'draft', 'human', ${str(s.category)}, ${lit(s.title)}, ${lit(s.summary)}, ${lit(s.objectives)}, ${lit(s.prerequisites)}, ${lit(s.sections)}, ${lit(s.sectionSupport)}, ${str(SYNTHETIC_SOURCE_NOTE)}, ${s.version});`);
    for (const c of s.checklist) {
      out.push(`insert into public.skill_checklist_items (id, skill_id, position, phase, text, critical, support) values (${str(c.id)}::uuid, ${str(s.id)}::uuid, ${c.position}, ${str(c.phase)}, ${lit(c.text)}, ${c.critical}, ${str(c.support)});`);
    }
    out.push(`insert into public.skill_revisions (skill_id, version, summary) values (${str(s.id)}::uuid, ${s.version}, ${lit(s.revision)});`);
    out.push(`update public.skill_items set status = 'published', approved_at = now(), published_at = now() where id = ${str(s.id)}::uuid;`);
    out.push("end if; end $seed$;");
  }
  out.push("commit;");
  return out.join("\n") + "\n";
}
