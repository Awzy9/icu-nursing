// Builds src/content/draft-register.json: COUNTS ONLY (no titles, no clinical text) describing the unpublished clinical drafts held in content/drafts.
// Shown on the staff-only /admin/content page so the content-management view can say what exists outside the database, whether it passes its
// validator, and that none of it is reviewed. The file is deterministic (no timestamps); CI fails if it is stale. Nothing here imports or publishes a draft.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { validateDraft, parseFrontMatter, parseMcqs } from "../src/lib/draft-validator";
import { validateSkillDraft, validateSkillSet } from "../src/lib/skill-draft-validator";
import { validateMedicationDraft, validateMedicationSet } from "../src/lib/medication-draft-validator";
import { validateScenarioDraft, validateScenarioSet } from "../src/lib/scenario-draft-validator";
import { validateEquipmentDraft, validateEquipmentSet } from "../src/lib/equipment-draft-validator";
import { loadKnownSources, loadSkillDrafts } from "./validate-skill-drafts";
import { loadMedicationDrafts, loadMedicationLabels, loadMedicationPlan, loadGuidelineSources } from "./validate-medication-drafts";
import { loadScenarioDrafts, loadScenarioKnownSources } from "./validate-scenario-drafts";
import { loadEquipmentDrafts } from "./validate-equipment-drafts";
import { validatePracticeDraft, validatePracticeSet } from "../src/lib/practice-draft-validator";
import { loadPracticeDrafts } from "./validate-practice-drafts";

type Tally = Record<string, number>;
const tally = (xs: string[]): Tally => xs.reduce<Tally>((a, x) => ({ ...a, [x]: (a[x] ?? 0) + 1 }), {});
export interface RegisterRow { total: number; validator_issues: number; clinically_reviewed: number; evidence: Tally; extra?: Record<string, number> }
export type DraftRegister = { note: string; types: Record<string, RegisterRow> };

export function buildDraftRegister(root = "."): DraftRegister {
  const base = path.join(root, "content/drafts");
  // Topics (markdown) and MCQs inside them
  const topicTexts: string[] = []; let mcqs = 0;
  for (const d of readdirSync(base).filter((x) => /^batch-\d+$/.test(x)).sort()) for (const f of readdirSync(path.join(base, d)).filter((x) => x.endsWith(".md")).sort()) { const t = readFileSync(path.join(base, d, f), "utf8"); topicTexts.push(t); mcqs += parseMcqs(t).length; }
  const topicIssues = topicTexts.reduce((n, t) => n + validateDraft(t).length, 0);
  const topicFm = topicTexts.map((t) => parseFrontMatter(t));
  const xq = readdirSync(path.join(base, "mcq-expansion")).filter((f) => /^XQ-\d\d-.*\.md$/.test(f)).map((f) => readFileSync(path.join(base, "mcq-expansion", f), "utf8"));
  const xqCount = xq.reduce((n, t) => n + parseMcqs(t).length, 0);

  const skills = loadSkillDrafts(root); const sk = loadKnownSources(root);
  const meds = loadMedicationDrafts(root); const plan = loadMedicationPlan(root);
  const medKnown = new Set([...loadMedicationLabels(root), ...loadGuidelineSources(root), "S-FDA-PUMP", "S-AHRQ-TS"]);
  const scs = loadScenarioDrafts(root); const scKnown = loadScenarioKnownSources(root);
  const eqs = loadEquipmentDrafts(root);
  const prs = loadPracticeDrafts(root);

  return {
    note: "Counts only. No titles or clinical text. Generated by scripts/build-draft-register.ts; none of these drafts is reviewed, imported or published.",
    types: {
      topics: { total: topicTexts.length, validator_issues: topicIssues, clinically_reviewed: topicFm.filter((f) => f.clinically_reviewed === "true").length, evidence: {}, extra: { titled_partial_evidence: topicFm.filter((f) => /partial/i.test(f.title ?? "")).length } },
      mcqs: { total: mcqs + xqCount, validator_issues: 0, clinically_reviewed: 0, evidence: {}, extra: { in_topic_drafts: mcqs, expansion_drafts: xqCount } },
      skills: { total: skills.length, validator_issues: skills.flatMap((d) => validateSkillDraft(d, sk)).length + validateSkillSet(skills).length, clinically_reviewed: skills.filter((d) => d.clinically_reviewed).length, evidence: tally(skills.map((d) => d.evidence_status)) },
      medications: { total: meds.length, validator_issues: meds.flatMap((d) => validateMedicationDraft(d, medKnown, plan)).length + validateMedicationSet(meds, plan).length, clinically_reviewed: meds.filter((d) => d.clinically_reviewed || d.pharmacist_reviewed).length, evidence: tally(meds.map((d) => d.evidence_status)) },
      scenarios: { total: scs.length, validator_issues: scs.flatMap((d) => validateScenarioDraft(d, scKnown)).length + validateScenarioSet(scs).length, clinically_reviewed: scs.filter((d) => d.clinically_reviewed).length, evidence: tally(scs.map((d) => d.evidence_status)), extra: { decision_graph: scs.filter((d) => d.spec_level === "decision_graph").length, outline: scs.filter((d) => d.spec_level === "outline").length } },
      equipment: { total: eqs.length, validator_issues: eqs.flatMap((d) => validateEquipmentDraft(d, scKnown)).length + validateEquipmentSet(eqs).length, clinically_reviewed: eqs.filter((d) => d.clinically_reviewed).length, evidence: tally(eqs.map((d) => d.evidence_status)) },
      practice: { total: prs.length, validator_issues: prs.flatMap((d) => validatePracticeDraft(d, scKnown)).length + validatePracticeSet(prs).length, clinically_reviewed: prs.filter((d) => d.clinically_reviewed).length, evidence: tally(prs.map((d) => d.evidence_status)) },
    },
  };
}
export const REGISTER_PATH = "src/content/draft-register.json";
if (process.argv[1]?.endsWith("build-draft-register.ts")) {
  const out = JSON.stringify(buildDraftRegister(), null, 2) + "\n";
  writeFileSync(REGISTER_PATH, out);
  console.log(`wrote ${REGISTER_PATH}`);
}
