/**
 * Generates supabase/seed.sql from the synthetic demo content in src/content/demo.ts so the demo
 * data exists in exactly one place. Run: npx tsx scripts/generate-seed.ts
 * The seed is DEVELOPMENT ONLY: it inserts topics of kind 'demo_synthetic' that are NOT clinically
 * reviewed and are labelled as such in the UI. Never apply it to a production clinical database.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { DEMO_DOMAINS, DEMO_TOPICS, demoActions, demoReferences, demoSections } from "../src/content/demo";

const q = (s: string | null | undefined) => (s == null ? "null" : `'${s.replace(/'/g, "''")}'`);
const j = (o: unknown) => `${q(JSON.stringify(o))}::jsonb`;

const lines: string[] = [
  "-- GENERATED by scripts/generate-seed.ts - do not edit by hand.",
  "-- DEVELOPMENT ONLY: synthetic demonstration topics (kind = demo_synthetic). Not clinical content, not reviewed.",
  "begin;",
];

for (const t of DEMO_TOPICS) {
  const domain = DEMO_DOMAINS.find((d) => d.slug === t.domainSlug)!;
  const sections = demoSections(t).map((s, i) => ({ id: s.id, kind: s.kind, sort: i, title: s.title, body: s.body }));
  const actions = demoActions(t).map((a, i) => ({ id: a.id, scope: a.scope, text: a.text, institutional_protocol_required: a.institutionalProtocolRequired, jurisdiction_note: a.jurisdictionNote, sort: i }));
  const references = demoReferences(t).map((r) => ({ organization: r.organization, title: r.title, url: r.url, version_label: r.versionLabel, is_draft_guideline: r.isDraftGuideline, last_checked: r.lastChecked, citation: r.citation, pinpoint: r.pinpoint, independently_written_note: r.independentlyWritten }));
  const snapshot = { title: t.title, summary: t.summary, level: t.level, est_minutes: t.minutes, guideline_note: null, origin: "human", sections, actions, references, images: [], reviewer_roles: [] };
  lines.push(
    `insert into public.topics (id, domain_id, slug, kind, status, title, summary, level, est_minutes, author_id)`,
    `  select ${q(t.id)}::uuid, id, ${q(t.slug)}, 'demo_synthetic', 'published', ${j(t.title)}, ${j(t.summary)}, ${q(t.level)}::learner_level, ${t.minutes}, null`,
    `  from public.nursing_domains where slug = ${q(domain.slug)} on conflict (id) do nothing;`,
    `insert into public.content_versions (id, topic_id, version_no, status, snapshot, required_review_roles, origin, published_at)`,
    `  values (${q(t.id.replace("10000000", "20000000"))}::uuid, ${q(t.id)}::uuid, 1, 'published', ${j(snapshot)}, '{NE}', 'human', now()) on conflict (id) do nothing;`,
    `update public.topics set published_version_id = ${q(t.id.replace("10000000", "20000000"))}::uuid, first_published_at = now() where id = ${q(t.id)}::uuid and published_version_id is null;`,
  );
}
lines.push("commit;", "");
writeFileSync(path.resolve(__dirname, "../supabase/seed.sql"), lines.join("\n"));
console.log(`seed.sql written (${DEMO_TOPICS.length} demo topics)`);
